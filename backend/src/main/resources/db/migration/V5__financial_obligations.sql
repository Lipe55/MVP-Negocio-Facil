-- Obligation -> installments -> settlements -> immutable balance movements.
-- Legacy due dates are deliberately unknown, never inferred from competence.
CREATE TABLE financial_recurrences (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id),
 kind VARCHAR(20) NOT NULL DEFAULT 'DESPESA' CHECK(kind='DESPESA'),
 description VARCHAR(500) NOT NULL CHECK(btrim(description)<>''),
 amount NUMERIC(16,2) NOT NULL CHECK(amount>0), account_id BIGINT NOT NULL, category_id BIGINT NOT NULL,
 first_due_date DATE NOT NULL, occurrences INTEGER NOT NULL CHECK(occurrences BETWEEN 1 AND 60),
 active BOOLEAN NOT NULL DEFAULT TRUE, notes VARCHAR(3000),
 request_id UUID NOT NULL, request_hash VARCHAR(64) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,company_id), UNIQUE(company_id,request_id),
 FOREIGN KEY(account_id,company_id) REFERENCES financial_accounts(id,company_id),
 FOREIGN KEY(category_id,company_id,kind) REFERENCES financial_categories(id,company_id,kind)
);
CREATE TABLE financial_obligations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), kind VARCHAR(20) NOT NULL CHECK(kind IN ('RECEITA','DESPESA')),
 description VARCHAR(500) NOT NULL CHECK(btrim(description)<>''),
 total_amount NUMERIC(16,2) NOT NULL CHECK(total_amount>0),
 installment_count INTEGER NOT NULL CHECK(installment_count BETWEEN 1 AND 120),
 source VARCHAR(20) NOT NULL CHECK(source IN ('LEGACY','QUICK','OBLIGATION','RECURRENCE')),
 recurrence_id BIGINT, occurrence_number INTEGER,
 request_id UUID NOT NULL, request_hash VARCHAR(64) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,company_id), UNIQUE(id,company_id,kind), UNIQUE(company_id,request_id),
 UNIQUE(recurrence_id,occurrence_number),
 FOREIGN KEY(recurrence_id,company_id) REFERENCES financial_recurrences(id,company_id),
 CHECK((recurrence_id IS NULL AND occurrence_number IS NULL AND source<>'RECURRENCE') OR
       (recurrence_id IS NOT NULL AND occurrence_number IS NOT NULL AND occurrence_number BETWEEN 1 AND 60 AND source='RECURRENCE' AND kind='DESPESA' AND installment_count=1))
);

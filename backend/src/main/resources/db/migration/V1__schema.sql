CREATE TABLE companies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL, document VARCHAR(20), phone VARCHAR(20) NOT NULL,
 next_quote_number BIGINT NOT NULL DEFAULT 1,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id),
 name VARCHAR(160) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role='ADMIN'), created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX users_company_idx ON users(company_id);
CREATE TABLE customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id),
 name VARCHAR(160) NOT NULL, phone VARCHAR(20) NOT NULL, email VARCHAR(254), document VARCHAR(20), notes VARCHAR(3000),
 archived_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,company_id)
);
CREATE INDEX customers_company_name_idx ON customers(company_id,lower(name));
CREATE TABLE quotations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id), customer_id BIGINT NOT NULL,
 number BIGINT NOT NULL, status VARCHAR(20) NOT NULL CHECK(status IN ('RASCUNHO','AGUARDANDO','ACEITO','RECUSADO','EXPIRADO')),
 valid_until DATE NOT NULL, notes VARCHAR(3000), subtotal NUMERIC(16,2) NOT NULL CHECK(subtotal>=0),
 discount NUMERIC(16,2) NOT NULL CHECK(discount>=0 AND discount<=subtotal), total NUMERIC(16,2) NOT NULL CHECK(total=subtotal-discount),
 public_token VARCHAR(64) UNIQUE, sent_at TIMESTAMPTZ, responded_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(company_id,number), FOREIGN KEY(customer_id,company_id) REFERENCES customers(id,company_id),
 CHECK ((status='RASCUNHO' AND public_token IS NULL AND sent_at IS NULL) OR (status<>'RASCUNHO' AND public_token IS NOT NULL AND sent_at IS NOT NULL)),
 CHECK ((status IN ('ACEITO','RECUSADO') AND responded_at IS NOT NULL) OR (status NOT IN ('ACEITO','RECUSADO') AND responded_at IS NULL))
);
CREATE INDEX quotations_company_status_idx ON quotations(company_id,status);
CREATE INDEX quotations_company_created_idx ON quotations(company_id,created_at DESC);
CREATE INDEX quotations_customer_idx ON quotations(customer_id);
CREATE TABLE quotation_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, quotation_id BIGINT NOT NULL REFERENCES quotations(id) ON DELETE CASCADE,
 description VARCHAR(500) NOT NULL, quantity NUMERIC(12,3) NOT NULL CHECK(quantity>0),
 unit_price NUMERIC(16,2) NOT NULL CHECK(unit_price>=0), total NUMERIC(16,2) NOT NULL CHECK(total>=0)
);
CREATE INDEX quotation_items_quote_idx ON quotation_items(quotation_id);
CREATE TABLE spring_session (
 primary_id CHAR(36) PRIMARY KEY, session_id CHAR(36) NOT NULL UNIQUE, creation_time BIGINT NOT NULL,
 last_access_time BIGINT NOT NULL, max_inactive_interval INT NOT NULL, expiry_time BIGINT NOT NULL, principal_name VARCHAR(100)
);
CREATE INDEX spring_session_expiry_idx ON spring_session(expiry_time);
CREATE INDEX spring_session_principal_idx ON spring_session(principal_name);
CREATE TABLE spring_session_attributes (
 session_primary_id CHAR(36) NOT NULL REFERENCES spring_session(primary_id) ON DELETE CASCADE,
 attribute_name VARCHAR(200) NOT NULL, attribute_bytes BYTEA NOT NULL,
 PRIMARY KEY(session_primary_id,attribute_name)
);

ALTER TABLE quotations ADD UNIQUE (id, company_id);
ALTER TABLE quotation_items ADD UNIQUE (id, quotation_id);
ALTER TABLE users ADD UNIQUE (id, company_id);

CREATE TABLE fiscal_invoices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id),
 imported_by BIGINT NOT NULL,
 customer_id BIGINT,
 quotation_id BIGINT,
 quotation_item_id BIGINT,
 obligation_id BIGINT,
 obligation_kind VARCHAR(20) GENERATED ALWAYS AS ('RECEITA') STORED,
 number TEXT NOT NULL,
 access_key VARCHAR(50) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('VALIDA','CANCELADA','SUBSTITUIDA','NAO_VERIFICADA')),
 issued_on DATE NOT NULL,
 competence DATE,
 provider_document VARCHAR(14) NOT NULL,
 provider_name TEXT,
 recipient_document VARCHAR(14),
 recipient_name TEXT,
 municipality TEXT,
 description TEXT,
 service_code TEXT,
 gross NUMERIC(16,2),
 net NUMERIC(16,2),
 amounts JSONB NOT NULL,
 xml_hash CHAR(64) NOT NULL,
 xml BYTEA NOT NULL CHECK (octet_length(xml) BETWEEN 1 AND 1048576),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE (company_id, access_key),
 UNIQUE (company_id, xml_hash),
 FOREIGN KEY (imported_by,company_id) REFERENCES users(id,company_id),
 FOREIGN KEY (customer_id,company_id) REFERENCES customers(id,company_id),
 FOREIGN KEY (quotation_id,company_id) REFERENCES quotations(id,company_id),
 FOREIGN KEY (quotation_item_id,quotation_id) REFERENCES quotation_items(id,quotation_id) ON DELETE SET NULL (quotation_item_id),
 FOREIGN KEY (obligation_id,company_id,obligation_kind) REFERENCES financial_obligations(id,company_id,kind),
 CHECK (quotation_item_id IS NULL OR quotation_id IS NOT NULL)
);
CREATE INDEX fiscal_invoices_issued_idx ON fiscal_invoices(company_id,issued_on DESC,id DESC);
CREATE INDEX fiscal_invoices_competence_idx ON fiscal_invoices(company_id,competence);
CREATE INDEX fiscal_invoices_status_idx ON fiscal_invoices(company_id,status,issued_on);
CREATE INDEX fiscal_invoices_customer_idx ON fiscal_invoices(company_id,customer_id);

CREATE TABLE fiscal_audit (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 invoice_id BIGINT NOT NULL REFERENCES fiscal_invoices(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 operation VARCHAR(30) NOT NULL,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

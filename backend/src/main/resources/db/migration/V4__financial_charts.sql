-- Preferences only: no financial values are copied into a chart configuration.
CREATE TABLE financial_chart_panels (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), owner_id BIGINT NOT NULL,
 version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(company_id,owner_id), UNIQUE(id,company_id,owner_id),
 FOREIGN KEY(owner_id,company_id) REFERENCES users(id,company_id)
);
CREATE TABLE financial_charts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), owner_id BIGINT NOT NULL, panel_id BIGINT NOT NULL,
 config_data TEXT NOT NULL CHECK(length(config_data)<=16000 AND jsonb_typeof(config_data::jsonb)='object'),
 position INTEGER NOT NULL CHECK(position>=0 AND position<24), version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 FOREIGN KEY(owner_id,company_id) REFERENCES users(id,company_id),
 FOREIGN KEY(panel_id,company_id,owner_id) REFERENCES financial_chart_panels(id,company_id,owner_id)
);
CREATE INDEX financial_charts_owner_position_idx ON financial_charts(company_id,owner_id,position,id);
CREATE INDEX financial_movement_chart_period_idx ON financial_movements(company_id,effective_date,id);

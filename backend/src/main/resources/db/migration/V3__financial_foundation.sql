-- Foundation only: no installments, recurrence, cards or quotation integration.
CREATE TABLE financial_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), name VARCHAR(160) NOT NULL CHECK(btrim(name)<>''),
 type VARCHAR(20) NOT NULL CHECK(type IN ('BANCO','DINHEIRO')),
 primary_account BOOLEAN NOT NULL DEFAULT FALSE, active BOOLEAN NOT NULL DEFAULT TRUE,
 opening_balance NUMERIC(16,2) NOT NULL DEFAULT 0, opening_date DATE NOT NULL,
 version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,company_id), CHECK(NOT primary_account OR active)
);
CREATE UNIQUE INDEX financial_account_primary_uk ON financial_accounts(company_id) WHERE primary_account;
CREATE UNIQUE INDEX financial_account_name_uk ON financial_accounts(company_id,lower(name));
CREATE TABLE financial_categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), name VARCHAR(100) NOT NULL CHECK(btrim(name)<>''),
 kind VARCHAR(20) NOT NULL CHECK(kind IN ('RECEITA','DESPESA')),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,company_id,kind), UNIQUE(id,company_id)
);
CREATE UNIQUE INDEX financial_category_name_uk ON financial_categories(company_id,kind,lower(name));
CREATE TABLE financial_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), account_id BIGINT NOT NULL, category_id BIGINT,
 kind VARCHAR(20) NOT NULL CHECK(kind IN ('RECEITA','DESPESA','RETIRADA')),
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDENTE','LIQUIDADO','CANCELADO')),
 description VARCHAR(500) NOT NULL CHECK(btrim(description)<>''), notes VARCHAR(3000),
 amount NUMERIC(16,2) NOT NULL CHECK(amount>0), entry_date DATE NOT NULL,
 request_id UUID NOT NULL, request_hash VARCHAR(64) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,company_id), UNIQUE(company_id,request_id),
 FOREIGN KEY(account_id,company_id) REFERENCES financial_accounts(id,company_id),
 FOREIGN KEY(category_id,company_id,kind) REFERENCES financial_categories(id,company_id,kind),
 CHECK((kind='RETIRADA' AND category_id IS NULL) OR (kind<>'RETIRADA' AND category_id IS NOT NULL))
);
CREATE INDEX financial_entry_filters_idx ON financial_entries(company_id,entry_date DESC,id DESC);
CREATE INDEX financial_entry_account_idx ON financial_entries(company_id,account_id,status);
CREATE TABLE financial_settlements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), entry_id BIGINT NOT NULL, account_id BIGINT NOT NULL,
 amount NUMERIC(16,2) NOT NULL CHECK(amount>0), settlement_date DATE NOT NULL,
 reversed_at TIMESTAMPTZ, request_id UUID NOT NULL, request_hash VARCHAR(64) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,company_id), UNIQUE(company_id,request_id),
 FOREIGN KEY(entry_id,company_id) REFERENCES financial_entries(id,company_id),
 FOREIGN KEY(account_id,company_id) REFERENCES financial_accounts(id,company_id)
);
CREATE UNIQUE INDEX financial_settlement_active_uk ON financial_settlements(entry_id) WHERE reversed_at IS NULL;
CREATE TABLE financial_transfers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), source_account_id BIGINT NOT NULL, target_account_id BIGINT NOT NULL,
 amount NUMERIC(16,2) NOT NULL CHECK(amount>0), transfer_date DATE NOT NULL,
 description VARCHAR(500) NOT NULL, request_id UUID NOT NULL, request_hash VARCHAR(64) NOT NULL,
 canceled_at TIMESTAMPTZ, version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,company_id), UNIQUE(company_id,request_id), CHECK(source_account_id<>target_account_id),
 FOREIGN KEY(source_account_id,company_id) REFERENCES financial_accounts(id,company_id),
 FOREIGN KEY(target_account_id,company_id) REFERENCES financial_accounts(id,company_id)
);
CREATE TABLE financial_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), account_id BIGINT NOT NULL,
 settlement_id BIGINT, transfer_id BIGINT, reversal_of_id BIGINT,
 kind VARCHAR(30) NOT NULL CHECK(kind IN ('RECEBIMENTO','PAGAMENTO','RETIRADA','TRANSFERENCIA_ENTRADA','TRANSFERENCIA_SAIDA','ESTORNO')),
 amount NUMERIC(16,2) NOT NULL CHECK(amount<>0), effective_date DATE NOT NULL,
 description VARCHAR(600) NOT NULL, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(id,company_id),
 FOREIGN KEY(account_id,company_id) REFERENCES financial_accounts(id,company_id),
 FOREIGN KEY(settlement_id,company_id) REFERENCES financial_settlements(id,company_id),
 FOREIGN KEY(transfer_id,company_id) REFERENCES financial_transfers(id,company_id),
 FOREIGN KEY(reversal_of_id,company_id) REFERENCES financial_movements(id,company_id),
 CHECK(num_nonnulls(settlement_id,transfer_id,reversal_of_id)=1),
 CHECK((kind='ESTORNO' AND reversal_of_id IS NOT NULL) OR
       (kind IN ('RECEBIMENTO','PAGAMENTO','RETIRADA') AND settlement_id IS NOT NULL) OR
       (kind IN ('TRANSFERENCIA_ENTRADA','TRANSFERENCIA_SAIDA') AND transfer_id IS NOT NULL)),
 CHECK(kind='ESTORNO' OR (kind IN ('RECEBIMENTO','TRANSFERENCIA_ENTRADA') AND amount>0) OR
       (kind IN ('PAGAMENTO','RETIRADA','TRANSFERENCIA_SAIDA') AND amount<0))
);
CREATE UNIQUE INDEX financial_movement_settlement_uk ON financial_movements(settlement_id) WHERE settlement_id IS NOT NULL;
CREATE UNIQUE INDEX financial_movement_transfer_leg_uk ON financial_movements(transfer_id,account_id) WHERE transfer_id IS NOT NULL;
CREATE UNIQUE INDEX financial_movement_reversal_uk ON financial_movements(reversal_of_id) WHERE reversal_of_id IS NOT NULL;
CREATE INDEX financial_movement_statement_idx ON financial_movements(company_id,account_id,effective_date,id);
ALTER TABLE users ADD CONSTRAINT users_id_company_uk UNIQUE(id,company_id);
CREATE TABLE financial_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES companies(id), actor_id BIGINT,
 resource VARCHAR(30) NOT NULL, resource_id BIGINT NOT NULL, action VARCHAR(30) NOT NULL,
 before_data TEXT, after_data TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 FOREIGN KEY(actor_id,company_id) REFERENCES users(id,company_id)
);
CREATE INDEX financial_audit_resource_idx ON financial_audit(company_id,resource,resource_id,id);
-- Prevent rewriting the cash ledger or audit trail through ordinary UPDATE/DELETE.
CREATE FUNCTION financial_reject_rewrite() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'Financial ledger and history are append-only';
END;
$$;
CREATE TRIGGER financial_movements_immutable BEFORE UPDATE OR DELETE ON financial_movements
 FOR EACH ROW EXECUTE FUNCTION financial_reject_rewrite();
CREATE TRIGGER financial_audit_immutable BEFORE UPDATE OR DELETE ON financial_audit
 FOR EACH ROW EXECUTE FUNCTION financial_reject_rewrite();
